const DICT: Record<Lang, Record<Key, string>> = { pl: PL, en: EN }

export const LOCALE: Record<Lang, string> = { pl: 'pl-PL', en: 'en-US' }
export const LANG_NAME: Record<Lang, string> = { pl: 'Polish', en: 'English' }

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICT[lang]?.[key] ?? EN[key]
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`))
}

// Kod języka z systemu (np. "pl_PL.UTF-8") albo z odpowiedzi routera (np. "pl").
export function toLang(code: string | undefined | null): Lang | null {
  const c = (code ?? '').trim().toLowerCase()
  if (c.startsWith('pl')) return 'pl'
  if (c.startsWith('en')) return 'en'
  return null
}

export function num(lang: Lang, n: number, digits = 1): string {
  return n.toLocaleString(LOCALE[lang], { maximumFractionDigits: digits, minimumFractionDigits: digits })
}
